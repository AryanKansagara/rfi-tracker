test('public holidays load for a region from the holiday service', async ({ page }) => {
  const asked: string[] = []
  await page.route('https://date.nager.at/**', r => {
    asked.push(new URL(r.request().url()).pathname)
    const y = r.request().url().match(/(\d{4})\/GB/)![1]
    return r.fulfill({ json: [{ date: `${y}-12-25`, name: 'Christmas', global: true, counties: null, types: ['Public'] }, { date: `${y}-08-03`, name: 'Scotland', global: false, counties: ['GB-SCT'], types: ['Public'] }], headers: { 'access-control-allow-origin': '*' } })
  })
  await newProject(page)
  await page.getByRole('button', { name: 'Load', exact: true }).click()
  await expect(page.getByLabel(/^Holidays/)).toHaveValue('2025-12-25\n2026-12-25\n2027-12-25')
  expect(asked.sort()).toEqual([2025, 2026, 2027].map(y => `/api/v3/PublicHolidays/${y}/GB`))
  await page.route('https://date.nager.at/**', r => r.fulfill({ status: 404, headers: { 'access-control-allow-origin': '*' } }))
  await page.getByRole('button', { name: 'Load', exact: true }).click()
  await expect(page.getByText('No holiday data for GB')).toBeVisible()
  await expect(page.getByLabel(/^Holidays/)).toHaveValue('2025-12-25\n2026-12-25\n2027-12-25')
})

