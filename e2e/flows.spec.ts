test('JSON export holds the projects and no credentials', async ({ page }) => {
  await handProject(page)
  await page.goto('/settings')
  const [name, buf] = await download(page, page.getByRole('button', { name: 'Export all my data (JSON)' }))
  expect(name).toBe('ball-in-court-export-2026-11-06.json')
  const j = JSON.parse(buf.toString('utf8'))
  expect(j.projects[0].dataset.items).toHaveLength(3)
  expect(buf.toString('utf8')).not.toMatch(/supabase|access_token|apikey|sb-/i)
})

test('markup and script in a log stay text on every tab and in the report', async ({ page }) => {
  const x = '<img src=x onerror="window.__pwned=1"><script>window.__pwned=1</script>'
  const q = `"${x.replace(/"/g, '""')}"`
  await logOf(page, `Number,Title,Status,Ball in court,Assigned to,Created on,Due date\n1,${q},Open,${q},${q},2026-10-01,2026-10-08\n`)
  await expect(logRow(page, 'RFI 1')).toContainText(x)
  for (const t of ['Overview', 'Schedule', 'Parties', 'Actions', 'History', 'Data']) await openTab(page, t)
  await page.getByRole('link', { name: 'OAC report' }).click()
  await expect(page.locator('.report')).toContainText('<script>')
  expect(await page.evaluate(() => (window as unknown as { __pwned?: number }).__pwned)).toBeUndefined()
})
